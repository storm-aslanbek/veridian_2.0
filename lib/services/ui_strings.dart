import 'localization_service.dart';

/// Translates app-owned labels, optionally inserting a formatted value.
String uiText(String label, [Object? value]) {
  final entry = _labels[label];
  final translation = switch (LocalizationService().currentLanguage) {
    AppLanguage.en => entry?.$1 ?? label,
    AppLanguage.kk => entry?.$2 ?? label,
    AppLanguage.ru => label,
  };
  return value == null
      ? translation
      : translation.replaceAll('{0}', value.toString());
}

String cardTypeLabel(String type) => switch (type.toLowerCase()) {
      'debit' => uiText('Дебетовая'),
      'credit' => uiText('Кредитная'),
      _ => type,
    };

